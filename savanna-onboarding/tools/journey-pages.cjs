// Writes the Savanna journey pages (index.html, signup.html, ...). They are identical apart from data-page:
// journey/journey.js draws Savanna's frame and the page content. Run from savanna-onboarding/: node tools/journey-pages.cjs
const fs = require('fs'), path = require('path');
const pages = { index: 'home', login: 'login', signup: 'signup', dashboard: 'dashboard', profile: 'profile', takeover: 'takeover',
  passport: 'passport', jobs: 'jobs', apply: 'apply', employer: 'employer', settings: 'settings' };
for (const [file, id] of Object.entries(pages)) {
  fs.writeFileSync(path.join(__dirname, '..', file + '.html'), `<!doctype html>
<!-- Savanna learner journey page "${id}". Savanna's own stylesheets (vendor/, unchanged) + the module + journey/journey.js.
     Generated by tools/journey-pages.cjs: edit the generator, not this file. -->
<html lang="am">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Savanna</title>
  <meta name="theme-color" content="#002b56">
  <link rel="icon" href="data:image/svg+xml,%3Csvg xmlns=%22http://www.w3.org/2000/svg%22 viewBox=%220 0 100 100%22%3E%3Crect width=%22100%22 height=%22100%22 rx=%2215%22 fill=%22%23002b56%22/%3E%3Ctext x=%2250%22 y=%2270%22 font-size=%2260%22 font-family=%22sans-serif%22 font-weight=%22700%22 text-anchor=%22middle%22 fill=%22%23fff%22%3ES%3C/text%3E%3C/svg%3E">
  <link rel="stylesheet" href="vendor/savanna-static-pages/assets/css/application_alx.css">
  <link rel="stylesheet" href="vendor/savanna-static-pages/assets/css/app.css">
  <link rel="stylesheet" href="journey/journey.css">
  <script src="savanna-onboarding.js" defer></script>
  <script src="forms.js" defer></script>
  <script src="app.js" defer></script>
  <script src="journey/journey.js" defer></script>
</head>
<body data-page="${id}">
  <noscript><p lang="en">Savanna needs JavaScript for this demo.</p></noscript>
</body>
</html>
`);
}
console.log(Object.keys(pages).length, 'pages written');
